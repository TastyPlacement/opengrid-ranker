    <div class="flash flash-bad">The database is set up, but this folder isn't writable, so config.php couldn't be saved.
      Create a file named <b>config.php</b> next to install.php with the contents below, then submit this form again.</div>
    <textarea class="code" rows="14" readonly><?= e($configText) ?></textarea>
  <?php elseif ($err): ?>
    <div class="flash flash-bad"><?= e($err) ?></div>
  <?php endif; ?>
  <form method="post" class="form">
    <fieldset><legend>Database</legend>
      <label>Type
        <select name="driver" id="driver">
          <option value="mysql" <?= $f['driver'] === 'mysql' ? 'selected' : '' ?>>MySQL / MariaDB (use this on your host)</option>
          <option value="sqlite" <?= $f['driver'] === 'sqlite' ? 'selected' : '' ?>>SQLite (local testing only)</option>
        </select></label>
      <div id="mysqlFields" class="grid2">
        <label>Host <input name="host" value="<?= e($f['host']) ?>"></label>
        <label>Port <input name="port" value="<?= e($f['port']) ?>"></label>
        <label>Database name <input name="name" value="<?= e($f['name']) ?>"></label>
        <label>Database user <input name="user" value="<?= e($f['user']) ?>" autocomplete="off"></label>
        <label class="span2">Database password <input type="password" name="pass" value="<?= e($f['pass']) ?>" autocomplete="new-password"></label>
      </div>
    </fieldset>
    <fieldset><legend>Your login</legend>
      <div class="grid2">
        <label>Email <input type="email" name="email" value="<?= e($f['email']) ?>" required></label>
        <label>Password (10+ characters) <input type="password" name="password" required minlength="10" autocomplete="new-password"></label>
        <label>Tool name <input name="app_name" value="<?= e($f['app_name']) ?>"></label>
        <label>Timezone <input name="timezone" value="<?= e($f['timezone']) ?>" list="tzs"></label>
      </div>
      <datalist id="tzs"><?php foreach (['America/New_York', 'America/Chicago', 'America/Denver', 'America/Phoenix', 'America/Los_Angeles', 'UTC'] as $tz) echo '<option value="' . $tz . '">'; ?></datalist>
    </fieldset>
    <button class="btn btn-primary" type="submit">Install</button>
  </form>
</div>
