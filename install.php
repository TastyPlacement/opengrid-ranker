<?php
// One-time installer: tests the database, creates tables, writes config.php and the first login.
// It refuses to run again once an account exists.
define('APP', true);
define('ROOT', __DIR__);
require __DIR__ . '/lib/db.php';

function e($s) { return htmlspecialchars((string) $s, ENT_QUOTES, 'UTF-8'); }

$configPath = __DIR__ . '/config.php';
if (file_exists($configPath)) {
    $GLOBALS['CONFIG'] = require $configPath;
    try {
        $pdo = db_connect($GLOBALS['CONFIG']['db']);
        if ((int) $pdo->query('SELECT COUNT(*) FROM users')->fetchColumn() > 0) {
            exit('<p style="font-family:sans-serif;padding:40px">Already installed. <a href="login.php">Log in</a>. You can delete install.php from the server.</p>');
        }
    } catch (Throwable $e) { /* config exists but DB not ready; allow re-install */ }
}

$err = null; $configText = null;
$f = array_merge(['driver' => 'mysql', 'host' => 'localhost', 'port' => '3306', 'name' => '', 'user' => '', 'pass' => '',
    'email' => '', 'timezone' => 'America/Chicago', 'app_name' => 'OpenGrid Ranker'], $_POST);

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    try {
        if (!filter_var($f['email'], FILTER_VALIDATE_EMAIL)) throw new Exception('Enter a valid email for your login.');
        if (strlen($_POST['password'] ?? '') < 10) throw new Exception('Use a password of at least 10 characters.');
        if (!in_array($f['timezone'], timezone_identifiers_list(), true)) throw new Exception('Unknown timezone.');
        if ($f['driver'] === 'sqlite') {
            @mkdir(__DIR__ . '/data', 0775, true);
            file_put_contents(__DIR__ . '/data/.htaccess', "Require all denied\n");
            $db = ['driver' => 'sqlite', 'path' => __DIR__ . '/data/gridrank.sqlite'];
        } else {
            $db = ['driver' => 'mysql', 'host' => $f['host'], 'port' => (int) $f['port'], 'name' => $f['name'], 'user' => $f['user'], 'pass' => $f['pass']];
        }
        try { $pdo = db_connect($db); }
        catch (PDOException $ex) { throw new Exception('Could not connect to the database: ' . $ex->getMessage()); }
        run_schema($pdo, $db['driver']);

        $config = ['db' => $db, 'app_name' => trim($f['app_name']) ?: 'OpenGrid Ranker', 'timezone' => $f['timezone'], 'cron_key' => bin2hex(random_bytes(20))];
        $configText = "<?php\n// Generated by install.php. Keep this file private.\nreturn " . var_export($config, true) . ";\n";
        $existing = file_exists($configPath) ? (require $configPath) : null;
        if (is_array($existing) && ($existing['db'] ?? null) == $db) {
            // config.php was created by hand with matching settings; keep it.
        } elseif (@file_put_contents($configPath, $configText) === false) {
            throw new Exception('__WRITE__');
        }
        $pdo->prepare('INSERT INTO users (email, password_hash, created_at) VALUES (?,?,?)')
            ->execute([strtolower($f['email']), password_hash($_POST['password'], PASSWORD_DEFAULT), gmdate('Y-m-d H:i:s')]);
        $st = $pdo->prepare('INSERT INTO settings (k, v) VALUES (?, ?)');
        foreach (['demo_mode' => '1', 'default_grid' => '9', 'default_radius' => '5', 'default_zoom' => '13', 'default_mode' => 'standard',
                     'default_device' => 'desktop', 'default_language' => 'en'] as $k => $v) {
            try { $st->execute([$k, $v]); } catch (Throwable $ex) {}
        }
        header('Location: login.php?installed=1');
        exit;
    } catch (Exception $ex) {
        $err = $ex->getMessage();
    }
}
